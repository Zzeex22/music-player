const audio = document.getElementById('audio-engine');
const gridContainer = document.getElementById('songs-grid-container');
const lyricsContainer = document.getElementById('lyrics-container');
const lyricsText = document.getElementById('lyrics-text');
const mainTitle = document.getElementById('main-title');

const currentCover = document.getElementById('current-cover');
const currentTitle = document.getElementById('current-title');
const currentArtist = document.getElementById('current-artist');
const playBtnContainer = document.getElementById('play-btn-container');
const playIcon = document.getElementById('play-icon');
const prevBtn = document.getElementById('prev-btn');
const nextBtn = document.getElementById('next-btn');

const shuffleBtn = document.getElementById('shuffle-btn'); // Tarik elemen shuffle
const lyricsToggleBtn = document.getElementById('lyrics-toggle-btn');
const progressWrapper = document.getElementById('progress-wrapper');
const progressFill = document.getElementById('progress-fill');
const currentTimeEl = document.getElementById('current-time');
const totalDurationEl = document.getElementById('total-duration');
const volumeSlider = document.getElementById('volume-slider');

let currentSongIndex = 0;
let isPlaying = false;
let isLyricsVisible = false;
let isShuffle = false; // Status awal shuffle mati

// SISTEM TOGGLE SHUFFLE
shuffleBtn.addEventListener('click', () => {
    isShuffle = !isShuffle; // Balikkan status nyala/mati
    
    if (isShuffle) {
        // Efek nyala warna hijau khas Spotify
        shuffleBtn.style.filter = "brightness(1.5) drop-shadow(0 0 5px #1DB954)";
    } else {
        shuffleBtn.style.filter = "none";
    }
});

// SISTEM TOGGLE LIRIK
lyricsToggleBtn.addEventListener('click', () => {
    isLyricsVisible = !isLyricsVisible; 
    
    if (isLyricsVisible) {
        gridContainer.style.display = 'none';
        lyricsContainer.style.display = 'block';
        mainTitle.innerText = "Lirik Lagu";
        lyricsToggleBtn.style.filter = "brightness(1.5) drop-shadow(0 0 5px #1DB954)"; // Udah jadi hijau
    } else {
        gridContainer.style.display = 'grid';
        lyricsContainer.style.display = 'none';
        mainTitle.innerText = "Daftar Putar Elegan";
        lyricsToggleBtn.style.filter = "none";
    }
    updateLyricsDisplay();
});

function renderPlaylist() {
    gridContainer.innerHTML = '';
    playlist.forEach((song, index) => {
        const card = document.createElement('div');
        card.classList.add('album-card');
        card.innerHTML = `
            <img src="${song.coverSrc}" alt="Cover ${song.title}">
            <h3>${song.title}</h3>
            <p>${song.artist}</p>
        `;
        card.addEventListener('click', () => {
            selectAndPlaySong(index);
        });
        gridContainer.appendChild(card);
    });
}

function loadSong(index) {
    currentSongIndex = index;
    const song = playlist[index];
    audio.src = song.audioSrc;
    currentTitle.innerText = song.title;
    currentArtist.innerText = song.artist;
    currentCover.innerHTML = `<img src="${song.coverSrc}" alt="Current Cover">`;
    updateLyricsDisplay();
}

function updateLyricsDisplay() {
    if (playlist[currentSongIndex].lyrics) {
        lyricsText.innerText = playlist[currentSongIndex].lyrics;
    } else {
        lyricsText.innerText = "Lirik tidak tersedia untuk lagu ini.";
    }
}

function togglePlayPause() {
    if (isPlaying) {
        pauseSong();
    } else {
        playSong();
    }
}

function playSong() {
    isPlaying = true;
    audio.play();
    playIcon.src = "icons/pause.png"; 
}

function pauseSong() {
    isPlaying = false;
    audio.pause();
    playIcon.src = "icons/play.png"; 
}

function selectAndPlaySong(index) {
    loadSong(index);
    playSong();
}


function nextSong() {
    if (isShuffle) {

        let randomIndex;
        do {
            randomIndex = Math.floor(Math.random() * playlist.length);
        } while (randomIndex === currentSongIndex && playlist.length > 1); 
        selectAndPlaySong(randomIndex);
    } else {

        let nextIndex = currentSongIndex + 1;
        if (nextIndex >= playlist.length) nextIndex = 0;
        selectAndPlaySong(nextIndex);
    }
}

function prevSong() {
    let prevIndex = currentSongIndex - 1;
    if (prevIndex < 0) prevIndex = playlist.length - 1;
    selectAndPlaySong(prevIndex);
}

function updateProgressBar() {
    const { duration, currentTime } = audio;
    if (isNaN(duration)) return;

    const progressPercent = (currentTime / duration) * 100;
    progressFill.style.width = `${progressPercent}%`;

    let currentMin = Math.floor(currentTime / 60);
    let currentSec = Math.floor(currentTime % 60);
    if (currentSec < 10) currentSec = `0${currentSec}`;
    currentTimeEl.innerText = `${currentMin}:${currentSec}`;

    let totalMin = Math.floor(duration / 60);
    let totalSec = Math.floor(duration % 60);
    if (totalSec < 10) totalSec = `0${totalSec}`;
    totalDurationEl.innerText = `${totalMin}:${totalSec}`;
}

function setProgress(e) {
    const width = progressWrapper.clientWidth;
    const clickX = e.offsetX;
    const duration = audio.duration;
    if (!isNaN(duration)) {
        audio.currentTime = (clickX / width) * duration;
    }
}

playBtnContainer.addEventListener('click', togglePlayPause);
nextBtn.addEventListener('click', nextSong);
prevBtn.addEventListener('click', prevSong);
audio.addEventListener('timeupdate', updateProgressBar);
audio.addEventListener('ended', nextSong); // Panggil fungsi nextSong yang udah di-upgrade
progressWrapper.addEventListener('click', setProgress);
volumeSlider.addEventListener('input', (e) => { audio.volume = e.target.value; });

renderPlaylist();
loadSong(currentSongIndex);
audio.volume = volumeSlider.value;